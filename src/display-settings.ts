import { SpotifyPlus } from 'spotifyplus';
import { useSyncExternalStore } from 'react';
import { LyricsFont } from './theme/fonts';

export interface DisplaySettings {
    lineSpacing: number;
    fontSize: number;
    interludeDuration: number;
    font: LyricsFont;
    disableAi: boolean;
}

const storageKey = 'lyrics.display.settings';
const defaults: DisplaySettings = { lineSpacing: 100, fontSize: 100, interludeDuration: 4, font: 'apple', disableAi: false };

const fontOptions = [
    { label: 'Apple Music', value: 'apple' },
    { label: 'Beautiful Lyrics', value: 'beautiful' },
    { label: 'Spotify', value: 'spotify' },
    { label: 'System', value: 'system' },
];

const interludeOptions = [
    { label: 'Beautiful Lyrics (2 seconds)', value: '2' },
    { label: 'Spicy Lyrics (3 seconds)', value: '3' },
    { label: 'Spotify Plus (4 seconds)', value: '4' },
    { label: 'Apple Music (8 seconds)', value: '8' },
];

const percent = (value: unknown, min: number, max: number, fallback: number) => typeof value === 'number' && Number.isFinite(value) ? Math.max(min, Math.min(max, value)) : fallback;
const option = (value: unknown, options: { value: string }[]) => options.find(option => option.value === String(value))?.value;

function sanitize(stored: Partial<Record<keyof DisplaySettings, unknown>> | null | undefined): DisplaySettings {
    return {
        lineSpacing: percent(stored?.lineSpacing, 50, 200, defaults.lineSpacing),
        fontSize: percent(stored?.fontSize, 70, 140, defaults.fontSize),
        interludeDuration: Number(option(stored?.interludeDuration, interludeOptions) ?? defaults.interludeDuration),
        font: (option(stored?.font, fontOptions) ?? defaults.font) as LyricsFont,
        disableAi: typeof stored?.disableAi === 'boolean' ? stored.disableAi : defaults.disableAi,
    };
}

let current = sanitize(SpotifyPlus.Platform.Storage.get(storageKey));
const listeners = new Set<() => void>();

const items = [
    { id: 'lineSpacing', type: 'slider' as const, label: 'Line spacing', description: 'Space between lyric lines, as a percentage of the default.', value: current.lineSpacing, min: 50, max: 200, step: 10 },
    { id: 'fontSize', type: 'slider' as const, label: 'Font size', description: 'Lyrics text size, as a percentage of the default.', value: current.fontSize, min: 70, max: 140, step: 5 },
    { id: 'font', type: 'select' as const, label: 'Font', description: 'Typeface used for lyrics.', value: current.font as string, options: fontOptions },
    { id: 'interludeDuration', type: 'select' as const, label: 'Interlude duration', description: 'Minimum instrumental gap before the interlude dots appear.', value: String(current.interludeDuration), options: interludeOptions },
    { id: 'disableAi', type: 'toggle' as const, label: 'Disable AI lyrics', description: 'Only show lyrics that were not generated by AI.', value: current.disableAi },
];

SpotifyPlus.Settings.registerSetting({ title: 'Lyrics appearance', items });
SpotifyPlus.Events.on('settings.changed', (payload: unknown) => {
    if (!payload || typeof payload !== 'object' || !('id' in payload) || !('value' in payload)) return;

    const setting = payload as { id: string; value: unknown };
    const item = items.find(item => item.id === setting.id);
    if (!item) return;

    const next = sanitize({ ...current, [setting.id]: setting.value });
    const value = next[setting.id as keyof DisplaySettings];
    item.value = (item.type === 'select' ? String(value) : value) as never;

    current = next;
    SpotifyPlus.Platform.Storage.set(storageKey, current);
    listeners.forEach(listener => listener());
});

const subscribe = (listener: () => void) => {
    listeners.add(listener);
    return () => { listeners.delete(listener); };
};

export const getDisplaySettings = () => current;
export const useDisplaySettings = (): DisplaySettings => useSyncExternalStore(subscribe, getDisplaySettings);

/** Scales one of the default lyric text sizes by the font size setting. */
export const scaledFontSize = (size: number, settings: DisplaySettings) => Math.round(size * settings.fontSize / 100);
